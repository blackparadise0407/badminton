export function translate(
  language: Language,
  message: string,
  values: TranslationValues = {},
) {
  const requestError = message.match(/^Request failed \((\d+)\)$/);
  const key = requestError ? "Request failed ({status})" : message;
  const interpolatedValues = requestError
    ? { ...values, status: requestError[1] }
    : values;
  const translated =
    language === "vi" ? (vietnamese[key] ?? key) : key;

  return translated.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    String(interpolatedValues[name] ?? placeholder),
  );
}
